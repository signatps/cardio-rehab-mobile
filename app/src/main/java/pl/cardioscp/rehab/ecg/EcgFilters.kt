    fun apply(preset: EcgPreset, samples: DoubleArray): DoubleArray = when (preset) {
        EcgPreset.NONE -> samples.copyOf()
        EcgPreset.HZ32 -> fir(samples, B32)
        EcgPreset.HZ50 -> fir(samples, B50)
        EcgPreset.BASELINE -> fir(samples, B067)
        EcgPreset.CLINICAL -> fir(fir(samples, B067), B50)
    }

    private fun fir(input: DoubleArray, b: DoubleArray): DoubleArray {
        if (input.isEmpty()) return DoubleArray(0)
        val a = DoubleArray(b.size) { index -> if (index == 0) 1.0 else 0.0 }
        val pad = 3 * (b.size - 1)
        if (input.size < pad + 2) return input.copyOf()
        return filtfilt(input, a, b)
    }

    private fun filtfilt(input: DoubleArray, denom: DoubleArray, numer: DoubleArray): DoubleArray {
        val n = input.size
        val order = maxOf(denom.size, numer.size)
        val pad = 3 * (order - 1)
        val padded = DoubleArray(2 * pad + n)
        for (i in 0 until pad) {
            padded[i] = 2 * input[0] - input[pad + 1 - i]
            padded[2 * pad + n - i - 1] = 2 * input[n - 1] - input[n - pad + i]
        }
        for (i in 0 until n) padded[pad + i] = input[i]
        val forward = DoubleArray(padded.size)
        var state = DoubleArray(order)
        for (i in padded.indices) forward[i] = iir(padded[i], denom, numer, order, state)
        val reversed = DoubleArray(forward.size) { forward[forward.size - 1 - it] }
        state = DoubleArray(denom.size + 1)
        val back = DoubleArray(reversed.size)
        for (i in reversed.indices) back[i] = iir(reversed[i], denom, numer, denom.size, state)
        val flipped = DoubleArray(back.size) { back[back.size - 1 - it] }
        return DoubleArray(n) { flipped[pad + it] }
    }

    /** Transposed direct form II. Zwraca y, stan w `state` jest aktualizowany. */
    private fun iir(x: Double, denom: DoubleArray, numer: DoubleArray, length: Int, state: DoubleArray): Double {
        val y = state[0] + numer[0] * x
        var i = 0
        while (i < length - 2) {
            val n1 = if (i + 1 < denom.size) denom[i + 1] else 0.0
            val b1 = if (i + 1 < numer.size) numer[i + 1] else 0.0
            state[i] = state[i + 1] + b1 * x - n1 * y
            i++
        }
        val last = length - 2
        if (last >= 0 && last < state.size) {
            val n1 = if (last + 1 < denom.size) denom[last + 1] else 0.0
            val b1 = if (last + 1 < numer.size) numer[last + 1] else 0.0
            state[last] = b1 * x - n1 * y
        }
        return y
    }
